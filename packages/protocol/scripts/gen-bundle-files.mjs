// Builds src/bundleFiles.generated.ts: the script files the desktop app ships, derived from its build scripts and sources
// (apps/desktop/package.json build:*, tsconfig.main.json, vite.config.ts). Telemetry keeps a stack frame only when its
// file is one of these (src/telemetry.ts sanitizeFrame); anything else is "[frame removed]".
//
//   node scripts/gen-bundle-files.mjs          write the file
//   node scripts/gen-bundle-files.mjs --check  exit 1 when it is out of date
//
// - tsc (tsconfig.main.json, rootDir src, outDir dist): src/{main,preload,engine-host,shared,mcp-bridge}/**/*.ts -> dist/**/*.js
// - esbuild bundles: dist/preload/index.cjs, dist/mcp/bridge.cjs (shipped as resources/mcp/bridge.cjs),
//   dist/mastery-starters/chooser.cjs, and the copied dist/main/run/preload.cjs
// - vite (renderer): the exact dist/renderer/assets/<chunk>-<hash>.js names, read from the built output (separate file)
// - node_modules frames keep only the package name, for the app's direct dependencies.
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..', '..');
const desktop = join(root, 'apps', 'desktop');
const OUT = resolve(here, '..', 'src', 'bundleFiles.generated.ts');

function* walk(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name.startsWith('.')) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* walk(p); else yield p;
  }
}
const rel = (p) => relative(desktop, p).replace(/\\/g, '/');

// Fail-safe: without the desktop app's sources (the package built on its own) the lists are empty, so every frame is
// "[frame removed]"; nothing is ever let through by default.
const haveDesktop = existsSync(join(desktop, 'tsconfig.main.json')) && existsSync(join(desktop, 'package.json'));
const tsconfig = haveDesktop ? JSON.parse(readFileSync(join(desktop, 'tsconfig.main.json'), 'utf8')) : { include: [] };
const tscDirs = tsconfig.include.map((g) => g.replace(/\/\*\*\/\*\.ts$/, ''));
const files = new Set();
for (const d of tscDirs) for (const f of walk(join(desktop, d))) {
  if (/\.ts$/.test(f) && !/\.d\.ts$/.test(f)) files.add(rel(f).replace(/^src\//, 'dist/').replace(/\.ts$/, '.js'));
}
const pkg = haveDesktop ? JSON.parse(readFileSync(join(desktop, 'package.json'), 'utf8')) : { scripts: {}, dependencies: {} };
for (const script of Object.values(pkg.scripts)) {
  for (const m of String(script).matchAll(/--outfile=(dist\/[A-Za-z0-9._/-]+\.c?js)/g)) files.add(m[1]);
  for (const m of String(script).matchAll(/copyFileSync\('[^']+','(dist\/[A-Za-z0-9._/-]+\.c?js)'\)/g)) files.add(m[1]);
}
const packages = Object.keys({ ...(pkg.dependencies ?? {}) }).sort();

// Renderer assets: vite names them <chunk>-<content hash>.js, so they are only known after `vite build`. The exact names
// of every build seen so far are kept in a separate, append-only list (old app versions keep reporting their own files),
// read from apps/desktop/dist/renderer/assets after the renderer is built (the desktop build runs this again then).
const ASSETS_OUT = resolve(here, '..', 'src', 'rendererAssets.generated.ts');
const assetsDir = join(desktop, 'dist', 'renderer', 'assets');
const built = existsSync(assetsDir) ? readdirSync(assetsDir).filter((f) => /^[A-Za-z0-9._-]+\.js$/.test(f)).map((f) => `dist/renderer/assets/${f}`) : [];
const known = existsSync(ASSETS_OUT) ? [...readFileSync(ASSETS_OUT, 'utf8').matchAll(/"(dist\/renderer\/assets\/[A-Za-z0-9._-]+\.js)"/g)].map((m) => m[1]) : [];
const assets = new Set([...known, ...built]);

const list = (xs) => (xs.size === 0 && !Array.isArray(xs) ? '[]' : JSON.stringify([...xs].sort()).replace(/","/g, '",\n  "').replace(/^\["/, '[\n  "').replace(/"\]$/, '",\n]'));
const out = `// GENERATED by scripts/gen-bundle-files.mjs from apps/desktop's build scripts and sources. Do not edit; rerun the script.
// ${files.size} files, ${packages.length} packages.
/** Script files the app ships, relative to the app root (inside app.asar). */
export const APP_BUNDLE_FILES: readonly string[] = ${list(files)};
/** Direct dependencies: a node_modules frame is reported as node_modules/<package> only. */
export const APP_BUNDLE_PACKAGES: readonly string[] = ${list(packages)};
`;
const assetsOut = `// GENERATED by scripts/gen-bundle-files.mjs after \`vite build\`: the exact renderer script names (with their content hash)
// of every desktop build made from this repo, append-only. Do not edit; the desktop build adds the current build's names.
/** ${assets.size} renderer scripts. */
export const APP_RENDERER_ASSETS: readonly string[] = ${list(assets)};
`;
if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== out) { console.log(`bundleFiles.generated.ts is out of date (${files.size} files now)`); process.exit(1); }
  const missing = built.filter((f) => !known.includes(f));
  if (!existsSync(ASSETS_OUT) || missing.length) { console.log(`rendererAssets.generated.ts lacks ${missing.length} file(s) of the current build`); process.exit(1); }
  console.log(`up to date: ${files.size} bundle files, ${known.length} renderer assets`);
} else {
  writeFileSync(OUT, out);
  const cur = existsSync(ASSETS_OUT) ? readFileSync(ASSETS_OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  if (cur !== assetsOut) writeFileSync(ASSETS_OUT, assetsOut);
  console.log(`wrote ${relative(root, OUT)}: ${files.size} files, ${packages.length} packages; renderer assets ${assets.size} (${built.length} in the current build)`);
}
