// Builds src/messageTemplates.generated.ts: every error message the app's own code can raise, as a template.
// Telemetry (src/telemetry.ts) sends an error message ONLY as the id of one of these templates; anything that matches none
// becomes "[message removed]". The template text comes from our source code, never from the error, so no build name,
// path, user name or code can ride along.
//
//   node scripts/gen-message-templates.mjs          write the file
//   node scripts/gen-message-templates.mjs --check  exit 1 when the file is out of date (prints the difference count)
//
// Scans `new <Something>Error(<literal>)` with a '...', "..." or `...${x}...` literal in the app and site sources,
// tools/mastery-starters and packages/*/src. `${...}` becomes a placeholder; a template needs enough literal letters
// to be specific (one that is all placeholders would match anything and is skipped).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..', '..');
const OUT = resolve(here, '..', 'src', 'messageTemplates.generated.ts');
const DIRS = [...readdirSync(join(root, 'apps')).map((a) => `apps/${a}/src`), 'tools/mastery-starters', ...readdirSync(join(root, 'packages')).map((p) => `packages/${p}/src`)];

function* files(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === 'dist' || name.startsWith('.')) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* files(p);
    else if (/\.(ts|tsx|mts|cts|js|mjs|cjs|astro)$/.test(name) && !/\.generated\.ts$/.test(name) && !/\.test\./.test(name)) yield p;
  }
}

const CTOR = String.raw`new\s+([A-Z][A-Za-z0-9]*)\(\s*`;
const SINGLE = new RegExp(CTOR + String.raw`'((?:\\.|[^'\\\n])*)'\s*[,)]`, 'g');
const DOUBLE = new RegExp(CTOR + String.raw`"((?:\\.|[^"\\\n])*)"\s*[,)]`, 'g');
const TEMPLATE = new RegExp(CTOR + '`((?:\\\\.|\\$\\{(?:[^{}`]|\\{[^{}`]*\\})*\\}|[^`\\\\$]|\\$(?!\\{))*)`\\s*[,)]', 'g');
const unescape = (s) => s.replace(/\\(.)/g, (_, c) => ({ n: '\n', t: '\t', r: '' })[c] ?? c);

const errorClasses = new Set(['Error', 'TypeError', 'RangeError', 'SyntaxError', 'ReferenceError', 'EvalError', 'URIError', 'AggregateError']);
const sources = [];
for (const d of DIRS) for (const f of files(join(root, d))) sources.push([relative(root, f).replace(/\\/g, '/'), readFileSync(f, 'utf8')]);
for (const [, text] of sources) for (const m of text.matchAll(/class\s+([A-Z][A-Za-z0-9]*)\s+extends\s+([A-Z][A-Za-z0-9]*)/g)) {
  if (/Error$/.test(m[2]) || errorClasses.has(m[2])) errorClasses.add(m[1]);
}
// Second pass: classes extending the app's own error classes.
for (const [, text] of sources) for (const m of text.matchAll(/class\s+([A-Z][A-Za-z0-9]*)\s+extends\s+([A-Z][A-Za-z0-9]*)/g)) if (errorClasses.has(m[2])) errorClasses.add(m[1]);

const templates = new Map(); // text -> parts
const letters = (parts) => parts.join('').replace(/[^A-Za-z]/g, '').length;
for (const [, text] of sources) {
  for (const re of [SINGLE, DOUBLE, TEMPLATE]) {
    for (const m of text.matchAll(re)) {
      if (!errorClasses.has(m[1])) continue;
      const raw = m[2];
      const parts = re === TEMPLATE ? raw.split(/\$\{(?:[^{}`]|\{[^{}`]*\})*\}/).map(unescape) : [unescape(raw)];
      if (parts.join('').length > 300) continue;
      const need = parts.length === 1 ? 4 : 8;
      if (letters(parts) < need) continue;
      // A template whose literal text is only at one end and short would match too much; require a literal start or end of 4+ letters.
      if (parts.length > 1 && letters([parts[0]]) < 4 && letters([parts[parts.length - 1]]) < 4) continue;
      templates.set(parts.join('{x}'), parts);
    }
  }
}
// Error codes the app's own source spells out as string literals ('NOT_FOUND', "STORAGE_FAILED", ...).
const codes = new Set();
for (const [, text] of sources) for (const m of text.matchAll(/(['"`])([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+|[A-Z]{3,})\1/g)) if (m[2].length <= 40) codes.add(m[2]);
// Starter ids the release approved (feature counters starter.follow.{id}).
const approvals = join(root, 'tools', 'mastery-starters', 'approvals.json');
const starters = existsSync(approvals) ? [...new Set(JSON.parse(readFileSync(approvals, 'utf8')).approved ?? [])].filter((x) => typeof x === 'string').sort() : [];
const rows = [...templates.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([textOf, parts]) => [`app.${createHash('sha256').update(textOf).digest('hex').slice(0, 12)}`, parts]);
const out = `// GENERATED by scripts/gen-message-templates.mjs from the app's own source. Do not edit by hand; rerun the script.
// ${rows.length} templates, ${errorClasses.size} error classes, ${codes.size} codes.
/** [id, literal parts]: the message matches when it is parts.join(<anything>), whole. */
export const APP_MESSAGE_TEMPLATES: readonly (readonly [string, readonly string[]])[] = ${JSON.stringify(rows, null, 0).replace(/\],\[/g, '],\n  [').replace(/^\[\[/, '[\n  [').replace(/\]\]$/, '],\n]')};
/** Error class names declared in the app (plus the JavaScript built-ins). Any other name is reported as "Error". */
export const APP_ERROR_NAMES: readonly string[] = ${JSON.stringify([...errorClasses].sort())};
/** Starter ids approved for the release (tools/mastery-starters/approvals.json). */
export const APP_STARTER_IDS: readonly string[] = ${JSON.stringify(starters)};
/** Upper-case codes spelled out in the app's source. Any other \`code\` is dropped. */
export const APP_ERROR_CODES: readonly string[] = ${JSON.stringify([...codes].sort()).replace(/","/g, '", "')};
`;
if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur.replace(/\r\n/g, '\n') !== out) { console.log(`messageTemplates.generated.ts is out of date (${rows.length} templates now)`); process.exit(1); }
  console.log(`up to date: ${rows.length} templates`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${relative(root, OUT)}: ${rows.length} templates, ${errorClasses.size} error classes`);
}
