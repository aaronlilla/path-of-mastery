//! Port of the per-node state PassiveSpec.lua keeps on its local copy of each tree node
//! (Classes/PassiveSpec.lua `Init`, `BuildAllDependsAndPaths`). Static fields (dn, sd, linked
//! ids, ...) come from the processed tree (`treedata::TreeData`); the rest is spec-local mutable
//! state rebuilt by `BuildAllDependsAndPaths` on every allocation change, same as upstream.

use crate::treedata::{as_bool, as_i64, i64_list, str_list, TreeData};
use pom_engine::cjson::J;
use pom_engine::modparser::types::PMod;
use serde_json::Value;

/// An immutable string shared between every spec built from one tree: cloning a node copies a pointer, not the text.
#[derive(Clone, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct NStr(std::sync::Arc<str>);
impl NStr {
    pub fn as_str(&self) -> &str {
        &self.0
    }
}
impl std::ops::Deref for NStr {
    type Target = str;
    fn deref(&self) -> &str {
        &self.0
    }
}
impl std::borrow::Borrow<str> for NStr {
    fn borrow(&self) -> &str {
        &self.0
    }
}
impl AsRef<str> for NStr {
    fn as_ref(&self) -> &str {
        &self.0
    }
}
impl PartialEq<str> for NStr {
    fn eq(&self, o: &str) -> bool {
        &*self.0 == o
    }
}
impl PartialEq<&str> for NStr {
    fn eq(&self, o: &&str) -> bool {
        &*self.0 == *o
    }
}
impl PartialEq<String> for NStr {
    fn eq(&self, o: &String) -> bool {
        &*self.0 == o.as_str()
    }
}
impl PartialEq<NStr> for &str {
    fn eq(&self, o: &NStr) -> bool {
        *self == &*o.0
    }
}
impl PartialEq<NStr> for String {
    fn eq(&self, o: &NStr) -> bool {
        self.as_str() == &*o.0
    }
}
impl From<String> for NStr {
    fn from(s: String) -> NStr {
        NStr(s.into())
    }
}
impl From<&str> for NStr {
    fn from(s: &str) -> NStr {
        NStr(s.into())
    }
}
impl From<&String> for NStr {
    fn from(s: &String) -> NStr {
        NStr(s.as_str().into())
    }
}
impl std::fmt::Display for NStr {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}
impl std::fmt::Debug for NStr {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        std::fmt::Debug::fmt(&*self.0, f)
    }
}

#[derive(Clone, Debug, Default)]
pub struct ExpansionJewel {
    pub index: i64,
    pub size: i64,
    pub proxy: i64,
    pub parent: Option<i64>,
}

#[derive(Clone, Debug)]
pub struct ConqueredBy {
    pub id: f64,
    pub conqueror_type: String,
}

#[derive(Clone, Debug)]
pub struct Node {
    pub id: i64,
    pub kind: NStr,
    pub dn: NStr,
    pub sd: std::sync::Arc<Vec<String>>,
    pub ascendancy_name: Option<NStr>,
    pub group_id: Option<i64>,
    pub o: i64,
    pub oidx: i64,
    pub linked_ids: std::sync::Arc<Vec<i64>>,
    pub is_jewel_socket: bool,
    pub is_multiple_choice_option: bool,
    pub is_proxy: bool,
    pub group_is_proxy: bool,
    pub expansion_jewel: Option<ExpansionJewel>,
    pub mastery_effect_ids: std::sync::Arc<Vec<i64>>,
    pub is_tattoo: bool,
    pub override_type: Option<NStr>,

    // ---- spec-local mutable state (reset/rebuilt each BuildAllDependsAndPaths) ----
    pub alloc: bool,
    pub path_dist: i64,
    pub path: Vec<i64>,
    pub depends: Vec<i64>,
    pub connected_to_start: bool,
    pub visited: bool,
    pub distance_to_class_start: i64,
    pub intuitive_leap_likes_affecting: Vec<i64>,
    pub conquered_by: Option<ConqueredBy>,

    pub mod_key: NStr,
    pub mods: std::sync::Arc<Vec<PMod>>,
    /// dn/sd/mods/is_tattoo/override_type differ from the tree's pristine values, so
    /// `build_all_depends_and_paths` has to reset them; a clean node is skipped.
    pub dirty: bool,
    /// This spec's own copy (see `NodeMap::node_mut`).
    touched: bool,
}

impl Node {
    /// A synthetic node generated by `clusterjewel::build_subgraph` (`BuildSubgraph`'s
    /// hand-built node tables, e.g. the notable/socket/small entries it inserts straight into
    /// `subGraph.nodes` rather than copying from the tree).
    pub fn new_generated(id: i64, kind: String, dn: String, sd: Vec<String>, o: i64, oidx: i64, is_jewel_socket: bool, expansion_jewel: Option<ExpansionJewel>) -> Node {
        Node {
            id,
            kind: kind.into(),
            dn: dn.into(),
            sd: std::sync::Arc::new(sd),
            ascendancy_name: None,
            group_id: None,
            o,
            oidx,
            linked_ids: Default::default(),
            is_jewel_socket,
            is_multiple_choice_option: false,
            is_proxy: false,
            group_is_proxy: false,
            expansion_jewel,
            mastery_effect_ids: Default::default(),
            is_tattoo: false,
            override_type: None,
            alloc: false,
            path_dist: 1000,
            path: Vec::new(),
            depends: Vec::new(),
            connected_to_start: false,
            visited: false,
            distance_to_class_start: 0,
            intuitive_leap_likes_affecting: Vec::new(),
            conquered_by: None,
            mod_key: NStr::default(),
            mods: Default::default(),
            dirty: true,
            touched: false,
        }
    }

    pub fn from_tree(id: i64, v: J, tree: &TreeData) -> Node {
        let group_id = v.get("g").and_then(as_i64);
        let group_is_proxy = group_id
            .and_then(|g| tree.group(g))
            .map(|g| as_bool(g.get("isProxy").unwrap_or(J::NULL)))
            .unwrap_or(false);
        let expansion_jewel = v.get("expansionJewel").and_then(|ej| {
            if ej.is_null() {
                return None;
            }
            Some(ExpansionJewel {
                index: ej.get("index").and_then(as_i64).unwrap_or(0),
                size: ej.get("size").and_then(as_i64).unwrap_or(0),
                proxy: ej.get("proxy").and_then(as_i64).unwrap_or(0),
                parent: ej.get("parent").and_then(as_i64),
            })
        });
        let mastery_effect_ids = v
            .get("masteryEffects")
            .map(|me| match (me.as_array(), me.as_object()) {
                (Some(a), _) => a.iter().filter_map(|e| e.get("effect").and_then(as_i64)).collect(),
                (_, Some(o)) => {
                    let mut keys: Vec<usize> = o.keys().filter_map(|k| k.parse().ok()).collect();
                    keys.sort();
                    keys.into_iter()
                        .filter_map(|k| o.get(&k.to_string())?.get("effect").and_then(as_i64))
                        .collect()
                }
                _ => Vec::new(),
            })
            .unwrap_or_default();

        Node {
            id,
            kind: v.get("type").and_then(|t| t.as_str()).unwrap_or("Normal").into(),
            dn: v.get("dn").and_then(|t| t.as_str()).unwrap_or("").into(),
            sd: std::sync::Arc::new(str_list(v.get("sd").unwrap_or(J::NULL))),
            ascendancy_name: v.get("ascendancyName").and_then(|s| s.as_str()).map(|s| s.into()),
            group_id,
            o: v.get("o").and_then(as_i64).unwrap_or(0),
            oidx: v.get("oidx").and_then(as_i64).unwrap_or(0),
            linked_ids: std::sync::Arc::new(i64_list(v.get("linkedId").unwrap_or(J::NULL))),
            is_jewel_socket: as_bool(v.get("isJewelSocket").unwrap_or(J::NULL)),
            is_multiple_choice_option: as_bool(v.get("isMultipleChoiceOption").unwrap_or(J::NULL)),
            is_proxy: as_bool(v.get("isProxy").unwrap_or(J::NULL)),
            group_is_proxy,
            expansion_jewel,
            mastery_effect_ids: std::sync::Arc::new(mastery_effect_ids),
            is_tattoo: false,
            override_type: None,

            alloc: false,
            path_dist: 1000,
            path: Vec::new(),
            depends: Vec::new(),
            connected_to_start: false,
            visited: false,
            distance_to_class_start: 0,
            intuitive_leap_likes_affecting: Vec::new(),
            conquered_by: None,

            mod_key: NStr::default(),
            mods: Default::default(),
            dirty: false,
            touched: false,
        }
    }
}

/// Integer hasher for node-id maps (Fx-style multiply). Node maps are looked up thousands of times per spec
/// build; nothing depends on their iteration order, which was already random per process.
#[derive(Default, Clone, Copy)]
pub struct IdHasher(u64);
impl std::hash::Hasher for IdHasher {
    fn write(&mut self, bytes: &[u8]) {
        for &b in bytes {
            self.0 = (self.0.rotate_left(5) ^ b as u64).wrapping_mul(0x517cc1b727220a95);
        }
    }
    fn write_i64(&mut self, v: i64) { self.0 = (self.0.rotate_left(5) ^ v as u64).wrapping_mul(0x517cc1b727220a95); }
    fn write_u64(&mut self, v: u64) { self.0 = (self.0.rotate_left(5) ^ v).wrapping_mul(0x517cc1b727220a95); }
    fn finish(&self) -> u64 { self.0 }
}
pub type NodeHashMap = std::collections::HashMap<i64, std::rc::Rc<Node>, std::hash::BuildHasherDefault<IdHasher>>;

/// A spec's nodes. They are shared with the pristine per-tree map a spec starts from (see `PassiveSpec::new`) and
/// copied only when the spec changes one (`node_mut`), so a spec owns the few hundred of the tree's thousands of
/// nodes it touched, and `touched` lists them. A node never touched still has the tree's values and the defaults
/// of every per-spec field, so a pass that resets per-spec state only has to visit `touched`. Reads go through
/// `Deref` to the map.
#[derive(Clone, Default)]
pub struct NodeMap {
    map: NodeHashMap,
    touched: Vec<i64>,
}

impl std::ops::Deref for NodeMap {
    type Target = NodeHashMap;
    fn deref(&self) -> &NodeHashMap {
        &self.map
    }
}

impl NodeMap {
    /// The node `id`, made this spec's own copy for writing.
    pub fn node_mut(&mut self, id: &i64) -> Option<&mut Node> {
        let rc = self.map.get_mut(id)?;
        if !rc.touched {
            let n = std::rc::Rc::make_mut(rc);
            n.touched = true;
            self.touched.push(*id);
            return Some(n);
        }
        Some(std::rc::Rc::make_mut(rc))
    }

    pub fn insert(&mut self, id: i64, mut node: Node) {
        if !self.map.get(&id).is_some_and(|n| n.touched) {
            self.touched.push(id);
        }
        node.touched = true;
        self.map.insert(id, std::rc::Rc::new(node));
    }

    /// A pristine map: nothing touched.
    pub fn pristine(map: NodeHashMap) -> NodeMap {
        NodeMap { map, touched: Vec::new() }
    }

    /// Ids of the nodes this spec has written, in first-write order.
    pub fn touched(&self) -> &[i64] {
        &self.touched
    }
}

/// The node `id` of `nodes`, made this spec's own copy for writing.
pub fn node_mut<'a>(nodes: &'a mut NodeMap, id: &i64) -> Option<&'a mut Node> {
    nodes.node_mut(id)
}
